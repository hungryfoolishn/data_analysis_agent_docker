"""Immutable dataframe snapshots for registered query-result assets."""

from __future__ import annotations

import os
import re
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

import pandas as pd
from pydantic import BaseModel, Field

from .assets import hash_dataframe, hash_file

_SNAPSHOT_ID_PATTERN = re.compile(r"^snap_[0-9a-f]{32}$")
_SHA256_PATTERN = re.compile(r"^[0-9a-f]{64}$")


def new_snapshot_id() -> str:
    """Return a unique, filesystem-safe snapshot identifier."""
    from uuid import uuid4

    return f"snap_{uuid4().hex}"


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


class SnapshotError(RuntimeError):
    """Base error for snapshot persistence."""


class SnapshotValidationError(SnapshotError, ValueError):
    """Raised when a snapshot identifier, path, or reference is invalid."""


class SnapshotNotFoundError(SnapshotError, FileNotFoundError):
    """Raised when a referenced snapshot file does not exist."""


class SnapshotFormatError(SnapshotError, ValueError):
    """Raised when a snapshot reference has an unsupported format."""


class SnapshotIntegrityError(SnapshotError):
    """Raised when snapshot physical or logical content checks fail."""


class SnapshotWriteError(SnapshotError):
    """Raised when a snapshot cannot be written atomically."""


class SnapshotReference(BaseModel):
    """A verifiable reference to one immutable dataframe snapshot."""

    snapshot_id: str
    snapshot_format: Literal["parquet"] = "parquet"
    snapshot_location: str
    snapshot_hash: str
    snapshot_hash_type: Literal["sha256"] = "sha256"
    content_hash: str
    row_count: int = Field(ge=0)
    column_count: int = Field(ge=0)
    created_at: str = Field(default_factory=utc_now_iso)


class SnapshotStore:
    """Store dataframe snapshots as Parquet files under a dedicated root."""

    def __init__(self, root_dir: Path | str) -> None:
        self.root = Path(root_dir).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    @staticmethod
    def _validate_snapshot_id(snapshot_id: str) -> None:
        if not isinstance(snapshot_id, str) or _SNAPSHOT_ID_PATTERN.fullmatch(
            snapshot_id
        ) is None:
            raise SnapshotValidationError(
                "snapshot_id must match 'snap_<32 lowercase hex characters>'"
            )

    def _path_for(self, snapshot_id: str) -> Path:
        self._validate_snapshot_id(snapshot_id)
        return self.root / f"{snapshot_id}.parquet"

    def _validate_reference_path(self, reference: SnapshotReference) -> Path:
        self._validate_snapshot_id(reference.snapshot_id)
        if reference.snapshot_format != "parquet":
            raise SnapshotFormatError(
                f"Unsupported snapshot format: {reference.snapshot_format}"
            )
        if reference.snapshot_hash_type != "sha256":
            raise SnapshotValidationError(
                f"Unsupported snapshot hash type: {reference.snapshot_hash_type}"
            )
        if _SHA256_PATTERN.fullmatch(reference.snapshot_hash) is None:
            raise SnapshotValidationError("snapshot_hash must be a SHA-256 digest")
        if _SHA256_PATTERN.fullmatch(reference.content_hash) is None:
            raise SnapshotValidationError("content_hash must be a SHA-256 digest")
        expected_location = f"{reference.snapshot_id}.parquet"
        if reference.snapshot_location != expected_location:
            raise SnapshotValidationError(
                "snapshot_location must be generated by SnapshotStore"
            )
        path = self.root / reference.snapshot_location
        resolved = path.resolve()
        try:
            resolved.relative_to(self.root)
        except ValueError as exc:
            raise SnapshotValidationError(
                "snapshot path escapes the SnapshotStore root"
            ) from exc
        return resolved

    def save(
        self,
        dataframe: pd.DataFrame,
        *,
        snapshot_id: str,
        content_hash: str | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> SnapshotReference:
        """Write one immutable Parquet snapshot and return its reference."""
        del metadata  # Snapshot metadata remains in DataAsset.source_metadata.
        if not isinstance(dataframe, pd.DataFrame):
            raise SnapshotValidationError("dataframe must be a pandas DataFrame")
        self._validate_snapshot_id(snapshot_id)

        computed_content_hash = hash_dataframe(dataframe)
        if content_hash is not None and content_hash != computed_content_hash:
            raise SnapshotValidationError(
                "content_hash does not match the supplied DataFrame"
            )

        final_path = self._path_for(snapshot_id)
        if final_path.exists():
            raise SnapshotValidationError(
                f"Snapshot already exists: {snapshot_id}"
            )

        fd, raw_temp = tempfile.mkstemp(
            dir=self.root, prefix=f".{snapshot_id}.", suffix=".tmp"
        )
        os.close(fd)
        temp_path = Path(raw_temp)
        try:
            dataframe.to_parquet(temp_path, index=False)
            with temp_path.open("rb") as handle:
                os.fsync(handle.fileno())
            restored = pd.read_parquet(temp_path)
            if (
                restored.shape != dataframe.shape
                or hash_dataframe(restored) != computed_content_hash
            ):
                raise SnapshotWriteError(
                    "Parquet round-trip failed before atomic replace"
                )
            snapshot_hash = hash_file(temp_path)
            os.replace(temp_path, final_path)
            try:
                dir_fd = os.open(self.root, os.O_RDONLY)
                try:
                    os.fsync(dir_fd)
                finally:
                    os.close(dir_fd)
            except OSError:
                # Directory fsync is best-effort; the file fsync already ran.
                pass
        except Exception as exc:
            temp_path.unlink(missing_ok=True)
            if isinstance(exc, SnapshotError):
                raise
            raise SnapshotWriteError(f"Unable to write snapshot: {exc}") from exc

        return SnapshotReference(
            snapshot_id=snapshot_id,
            snapshot_format="parquet",
            snapshot_location=final_path.name,
            snapshot_hash=snapshot_hash,
            snapshot_hash_type="sha256",
            content_hash=computed_content_hash,
            row_count=int(len(dataframe)),
            column_count=int(len(dataframe.columns)),
        )

    def load(self, reference: SnapshotReference) -> pd.DataFrame:
        """Load and fully verify a snapshot before returning its DataFrame."""
        path = self._validate_reference_path(reference)
        if not path.is_file():
            raise SnapshotNotFoundError(f"Snapshot file does not exist: {path}")

        actual_snapshot_hash = hash_file(path)
        if actual_snapshot_hash != reference.snapshot_hash:
            raise SnapshotIntegrityError(
                "Snapshot file hash does not match snapshot reference"
            )

        try:
            dataframe = pd.read_parquet(path)
        except Exception as exc:
            raise SnapshotIntegrityError(
                f"Unable to read snapshot file: {exc}"
            ) from exc

        if (
            len(dataframe) != reference.row_count
            or len(dataframe.columns) != reference.column_count
        ):
            raise SnapshotIntegrityError(
                "Snapshot shape does not match snapshot reference"
            )
        if hash_dataframe(dataframe) != reference.content_hash:
            raise SnapshotIntegrityError(
                "Snapshot DataFrame hash does not match content hash"
            )
        return dataframe

    def exists(self, reference: SnapshotReference) -> bool:
        """Return whether the referenced snapshot file exists (no integrity check)."""
        return self._validate_reference_path(reference).is_file()

    def delete(self, reference: SnapshotReference) -> None:
        """Delete a snapshot managed by this store; missing files are ignored."""
        path = self._validate_reference_path(reference)
        path.unlink(missing_ok=True)
